package com.pai.api.reports.domain;

import java.time.Instant;
import java.util.UUID;

/**
 * Dosis aplicada (con su atencion) para el reporte "Registro Diario". Lo produce
 * el modulo {@code attentions} a traves del puerto {@code RegistroDiarioQuery};
 * incluye el {@code patientId} para que {@code reports} cruce la identidad.
 */
public record RegistroDiarioDoseData(
    Long consecutive,
    Instant attentionDate,
    UUID patientId,
    String vaccineName,
    String vaccineCode,
    String doseLabel,
    String lotNumber,
    String laboratory,
    String syringe,
    String dropper,
    String observation,
    Instant applicationDate,
    String status,
    UUID attentionId,
    UUID vaccineId,
    UUID vaccinatorId,
    Boolean completeScheme,
    String syringeLot,
    String diluent,
    String pneumococcalType,
    Integer vialCount,
    Boolean paiwebRegistered,
    String paiwebNotRegisteredReason,
    String attentionObservations,
    Double latitude,
    Double longitude) {

  public RegistroDiarioDoseData(
      Long consecutive,
      Instant attentionDate,
      UUID patientId,
      String vaccineName,
      String vaccineCode,
      String doseLabel,
      String lotNumber,
      String laboratory,
      String syringe,
      String dropper,
      String observation,
      Instant applicationDate,
      String status,
      UUID attentionId,
      UUID vaccineId,
      UUID vaccinatorId,
      Boolean completeScheme,
      String syringeLot,
      String diluent,
      String pneumococcalType,
      Integer vialCount) {
    this(
        consecutive,
        attentionDate,
        patientId,
        vaccineName,
        vaccineCode,
        doseLabel,
        lotNumber,
        laboratory,
        syringe,
        dropper,
        observation,
        applicationDate,
        status,
        attentionId,
        vaccineId,
        vaccinatorId,
        completeScheme,
        syringeLot,
        diluent,
        pneumococcalType,
        vialCount,
        false,
        null,
        null,
        null,
        null);
  }

  public RegistroDiarioDoseData(
      Long consecutive,
      Instant attentionDate,
      UUID patientId,
      String vaccineName,
      String vaccineCode,
      String doseLabel,
      String lotNumber,
      String laboratory,
      String syringe,
      String dropper,
      String observation,
      Instant applicationDate,
      String status) {
    this(
        consecutive,
        attentionDate,
        patientId,
        vaccineName,
        vaccineCode,
        doseLabel,
        lotNumber,
        laboratory,
        syringe,
        dropper,
        observation,
        applicationDate,
        status,
        null,
        null,
        null,
        false,
        null,
        null,
        null,
        null,
        false,
        null,
        null,
        null,
        null);
  }
}
